"""Offline checks of the eval suite in ../evals (the evals themselves run with `claude plugin eval`).

The cases are generated by evals/build.py: they must be in sync with it, parse, and their
scaffolds must build a fixture whose regex graders fail before the update.
Run: python3 -m unittest discover -s plugins/dependency-updates/tests"""
import filecmp, importlib.util, os, re, subprocess, tempfile, unittest
from pathlib import Path

EVALS = Path(__file__).resolve().parent.parent / "evals"

try:
    import yaml
except ImportError:
    yaml = None


def load_build():
    spec = importlib.util.spec_from_file_location("build_evals", EVALS / "build.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def cases():
    return sorted(p.parent for p in EVALS.glob("*/case.yaml"))


class EvalSuiteTest(unittest.TestCase):
    def test_cases_match_the_generator(self):
        build = load_build()
        with tempfile.TemporaryDirectory() as d:
            build.HERE = Path(d)
            for name, e in build.ECOSYSTEMS.items():
                build.write_case(name, e)
            build.write_tradeoff()
            fresh = sorted(p.name for p in Path(d).iterdir())
            self.assertEqual(fresh, [c.name for c in cases()], "run evals/build.py")
            for name in fresh:
                cmp = filecmp.dircmp(Path(d) / name, EVALS / name)
                self.assertEqual((cmp.diff_files, cmp.left_only, cmp.right_only), ([], [], []),
                                 f"{name}: out of date, run evals/build.py")

    def test_every_ecosystem_has_a_case(self):
        names = {c.name for c in cases()}
        for eco in ("npm", "pnpm", "yarn-classic", "yarn-berry", "bun", "pip", "uv", "poetry", "go", "cargo",
                    "maven", "gradle-groovy", "gradle-kotlin-catalog", "nuget-cpm", "bundler", "composer",
                    "terraform", "helm", "pre-commit", "github-actions", "containers"):
            self.assertIn(eco, names)

    @unittest.skipIf(yaml is None, "PyYAML not installed")
    def test_cases_parse_and_scaffolds_build_the_fixture(self):
        for case_dir in cases():
            with self.subTest(case=case_dir.name):
                case = yaml.safe_load((case_dir / "case.yaml").read_text())
                self.assertEqual(case["schema_version"], "1.1")
                self.assertTrue(case["graders"])
                with tempfile.TemporaryDirectory() as ws:
                    subprocess.run(["bash", str(case_dir / case["context"]["scaffold_script"])], cwd=ws,
                                   check=True, capture_output=True, timeout=60)
                    snap = (Path(ws) / "REGISTRY_SNAPSHOT.md").read_text()
                    self.assertRegex(snap, r"\| 1\.4\.0 \| 20\d\d-\d\d-\d\dT")  # times filled in at run time
                    for g in case["graders"]:
                        if g["type"] == "regex":
                            path = Path(ws) / g["target"]["path"]
                            self.assertTrue(path.exists(), g["name"])
                            hit = bool(re.search(g["pattern"], path.read_text()))
                            # before any update: only the "new version" check fails
                            want = g["name"] != "manifest-updated"
                            self.assertEqual(hit if g.get("match") != "not_contains" else not hit, want, g["name"])


if __name__ == "__main__":
    unittest.main()
